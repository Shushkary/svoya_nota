// isoDay: 1 (Пн) … 7 (Вс)
export function isoDay(date) {
  const d = date.getDay();
  return d === 0 ? 7 : d;
}

export function planForDay(date) {
  return WEEK[isoDay(date) - 1];
}

// Утренняя отметка низкая → предложить мягкий день (не заменяя план принудительно).
export function suggestGentle(morningState) {
  if (!morningState) return false;
  const calm = Number(morningState.calm) || 3;
  const energy = Number(morningState.energy) || 3;
  return (calm + energy) / 2 <= 2;
}

